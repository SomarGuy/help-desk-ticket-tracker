PRIORITY_WEIGHTS = {"Low": 25, "Medium": 45, "High": 22, "Critical": 8}
CAT_WEIGHTS = {"Hardware": 24, "Software": 30, "Network": 20, "Account Access": 26}


def build(db_path: str, count: int, seed: int) -> None:
    rng = random.Random(seed)
    init_db(db_path)
    con = sqlite3.connect(db_path)
    now = utcnow()

    for name in TECHNICIANS:
        con.execute("INSERT INTO technicians (name) VALUES (?)", (name,))
    tech_ids = [r[0] for r in con.execute("SELECT id FROM technicians")]

    def note(tid, when, author, kind, body):
        con.execute("INSERT INTO notes (ticket_id, author, kind, body, created_at) "
                    "VALUES (?,?,?,?,?)", (tid, author, kind, body, to_text(when)))

    for _ in range(count):
        category = rng.choices(list(CAT_WEIGHTS), list(CAT_WEIGHTS.values()))[0]
        priority = rng.choices(list(PRIORITY_WEIGHTS), list(PRIORITY_WEIGHTS.values()))[0]
        title, desc, resolution = rng.choice(TEMPLATES[category])
        requester = rng.choice(REQUESTERS)
        created = now - timedelta(hours=rng.uniform(1, 24 * 21))   # within the last 3 weeks
        created = created.replace(microsecond=0)
        due = created + sla_delta(priority)
        assignee = rng.choice(tech_ids) if rng.random() < 0.85 else None
        state = rng.choices(["done", "open"], [62, 38])[0]

        status, resolved_at, res_text = "Open", None, None
        if state == "done":
            # Time to resolve: a random fraction/multiple of the SLA window, so some
            # tickets meet it and some miss it. Capped so it can't be in the future.
            hours = SLA_HOURS[priority] * rng.lognormvariate(-0.35, 0.65)
            resolved_at = min(created + timedelta(hours=hours), now - timedelta(minutes=5))
            resolved_at = resolved_at.replace(microsecond=0)
            status = rng.choices(["Resolved", "Closed"], [55, 45])[0]
            res_text = resolution
            assignee = assignee or rng.choice(tech_ids)
        else:
            # Open tickets are mostly recent (within ~1.6x their SLA window), so a
            # realistic minority are already past their due time.
            created = (now - timedelta(hours=rng.uniform(0.5, SLA_HOURS[priority] * 1.6))
                       ).replace(microsecond=0)
            due = created + sla_delta(priority)
            status = rng.choices(["Open", "In Progress", "Waiting on User"], [40, 40, 20])[0]
            if status != "Open" and assignee is None:
                assignee = rng.choice(tech_ids)

        cur = con.execute(
            "INSERT INTO tickets (title, description, requester, category, priority, status, "
            "assignee_id, created_at, updated_at, due_at, resolved_at, resolution) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
            (title, desc, requester, category, priority, status, assignee, to_text(created),
             to_text(resolved_at or created), to_text(due), to_text(resolved_at) if resolved_at else None,
             res_text))
        tid = cur.lastrowid

        # Resolution log entries
        note(tid, created, "System", "change",
             f"Ticket created ({priority} priority, SLA due in {SLA_HOURS[priority]}h).")
        tech_name = None
        if assignee:
            tech_name = con.execute("SELECT name FROM technicians WHERE id=?", (assignee,)).fetchone()[0]
            note(tid, created + timedelta(minutes=rng.randint(2, 40)), "System", "change",
                 f"Assigned to {tech_name}")
        if status != "Open" and tech_name:
            mid = created + timedelta(minutes=rng.randint(45, 240))
            if resolved_at:
                mid = min(mid, resolved_at - timedelta(minutes=1))
            note(tid, mid, tech_name, "note",
                 rng.choice(["Contacted the user and confirmed the symptoms.",
                             "Checked basic settings and tried the standard runbook steps.",
                             "Reproduced the problem on the user's device.",
                             "Waiting for the user to reply with a screenshot of the error."]))
        if resolved_at:
            note(tid, resolved_at, tech_name or "System", "resolution", res_text)
            note(tid, resolved_at, tech_name or "System", "change", f"Status Open -> {status}")
    con.commit()
    con.close()


def main() -> None:
    ap = argparse.ArgumentParser(description="Seed the ticket tracker with synthetic sample data.")
    ap.add_argument("--db", help="database path (default: instance/tickets.sqlite)")
    ap.add_argument("--count", type=int, default=60, help="number of sample tickets")
    ap.add_argument("--seed", type=int, default=42, help="random seed")
    args = ap.parse_args()
    db_path = args.db or create_app().config["DATABASE"]
    os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
    build(db_path, args.count, args.seed)
    print(f"Seeded {args.count} synthetic tickets into {db_path}")


if __name__ == "__main__":
    main()
