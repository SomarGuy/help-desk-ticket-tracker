#!/usr/bin/env python3
"""
Create the database and fill it with SYNTHETIC sample tickets.

Everything here is invented for demo purposes: the technician and requester
names are made up, and the tickets, notes and resolution times are generated by
a random number generator (fixed seed, so the same data every run). They are
NOT real incidents or real performance numbers.

Usage:
    python seed.py                 # (re)creates instance/tickets.sqlite with 60 tickets
    python seed.py --count 120 --seed 7
    python seed.py --db /tmp/demo.sqlite
WARNING: this deletes any existing tickets in the target database.
"""
